// Builds supabase/seed.sql from the candidate list. Wikidata details are included
// only for rows approved in docs/wikidata-matches.csv.

import { existsSync, writeFileSync } from 'node:fs';

import { readCsv } from './csv.mjs';

const MATCHES_PATH = 'docs/wikidata-matches.csv';

function sql(value) {
  return value ? `'${value.replaceAll("'", "''")}'` : 'null';
}

const approved = new Map(
  (existsSync(MATCHES_PATH) ? readCsv(MATCHES_PATH) : [])
    .filter((row) => row.approved.trim().toLowerCase() === 'yes')
    .map((row) => [row.name, row])
);

const people = readCsv('docs/seed-candidates.csv').map(({ name, home_party }) => {
  const match = approved.get(name) ?? {};
  const values = [
    name,
    home_party,
    match.wikidata_id,
    match.birth_date,
    match.photo_url,
    match.wikipedia_title,
  ].map(sql);
  return `  (${values.join(', ')}, true)`;
});

writeFileSync(
  'supabase/seed.sql',
  `-- Generated by scripts/generate-seed.mjs. Edit docs/seed-candidates.csv instead.

insert into public.races (office_id, cycle, name, general_date)
select id, 2028, '2028 President', '2028-11-07' from public.offices where name = 'President';

-- Phase boundaries are provisional until the 2028 calendar is set.
insert into public.seasons (race_id, phase, name, starts_at, ends_at)
select r.id, s.phase, s.name, s.starts_at::timestamptz, s.ends_at::timestamptz
from public.races r
cross join (values
  ('invisible_primary', '2028 Invisible Primary', '2027-01-01', '2028-01-01'),
  ('primary', '2028 Primary Season', '2028-01-01', '2028-07-01'),
  ('general', '2028 General Election', '2028-07-01', '2028-12-01'),
  ('full_cycle', '2028 Full Cycle', '2027-01-01', '2028-12-01')
) as s (phase, name, starts_at, ends_at)
where r.name = '2028 President';

insert into public.people (full_name, home_party, wikidata_id, birth_date, photo_url, wikipedia_title, verified) values
${people.join(',\n')};

-- Every person can be drafted as either a Democrat or a Republican.
insert into public.candidacies (person_id, race_id, party_code)
select p.id, r.id, party.code
from public.people p
cross join public.races r
cross join (values ('D'), ('R')) as party (code)
where r.name = '2028 President';
`
);

console.log(`Wrote ${people.length} people, ${approved.size} with approved Wikidata details.`);
